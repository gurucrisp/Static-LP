/**
  ******************************************************************************
  * @file    slave_ctrl_hw.c
  * @brief   Target implementation of slave_ctrl_hw.h.
  *
  * TIM2 is the free-running 1 MHz / 32-bit timer that already timestamps the
  * zero-cross edges (slave_zc.c). Two of its compare channels are used as
  * one-shot timers:
  *     CC2 : converter dead time   (-> SlaveCtrl_OnDeadtimeIrq)
  *     CC3 : zero-cross watchdog   (-> SlaveCtrl_OnWatchdogIrq)
  * The interrupt handler itself is TIM2_IRQHandler in stm32g0xx_it.c.
  ******************************************************************************
  */
#include "main.h"
#include "slave_ctrl_hw.h"
#include "slave_irq_prio.h"
#include "slave_meas.h"
#include "slave_zc.h"

void CtrlHw_Init(void)
{
    TIM2->DIER &= ~(TIM_DIER_CC1IE | TIM_DIER_CC2IE | TIM_DIER_CC3IE | TIM_DIER_CC4IE);
    TIM2->SR    = ~(TIM_SR_CC1IF | TIM_SR_CC2IF | TIM_SR_CC3IF | TIM_SR_CC4IF);
    HAL_NVIC_SetPriority(TIM2_IRQn, IRQ_PRIO_TIMING, 0);
    HAL_NVIC_EnableIRQ(TIM2_IRQn);
    SlaveMeas_TickIrqEnable();                  /* 20 kHz polarity guard */
}

uint32_t CtrlHw_NowUs(void) { return TIM2->CNT; }
uint32_t CtrlHw_NowMs(void) { return HAL_GetTick(); }

/* Arm one compare channel at an ABSOLUTE time. A compare only matches when the
 * counter EQUALS the value, so if the time has already passed (a higher
 * priority interrupt delayed us) the event is generated by hand - otherwise
 * it would wait for the 32-bit timer to wrap, about 71 minutes. */
static inline void Arm(volatile uint32_t *ccr, uint32_t at_us, uint32_t ie, uint32_t flag, uint32_t gen)
{
    *ccr        = at_us;
    TIM2->SR    = ~flag;
    TIM2->DIER |= ie;
    if ((int32_t)(TIM2->CNT - at_us) >= 0) TIM2->EGR = gen;
}

void CtrlHw_ArmDeadtime(uint32_t at_us)
{
    Arm(&TIM2->CCR2, at_us, TIM_DIER_CC2IE, TIM_SR_CC2IF, TIM_EGR_CC2G);
}

void CtrlHw_DisarmDeadtime(void)
{
    TIM2->DIER &= ~TIM_DIER_CC2IE;
    TIM2->SR    = ~TIM_SR_CC2IF;
}

void CtrlHw_ArmPredictOff(uint32_t at_us)
{
    Arm(&TIM2->CCR3, at_us, TIM_DIER_CC3IE, TIM_SR_CC3IF, TIM_EGR_CC3G);
}

void CtrlHw_DisarmPredictOff(void)
{
    TIM2->DIER &= ~TIM_DIER_CC3IE;
    TIM2->SR    = ~TIM_SR_CC3IF;
}

void CtrlHw_ArmWatchdog(uint32_t at_us)
{
    Arm(&TIM2->CCR4, at_us, TIM_DIER_CC4IE, TIM_SR_CC4IF, TIM_EGR_CC4G);
}

void CtrlHw_DisarmWatchdog(void)
{
    TIM2->DIER &= ~TIM_DIER_CC4IE;
    TIM2->SR    = ~TIM_SR_CC4IF;
}

int8_t CtrlHw_SignLatest(uint8_t strong)
{
    return SlaveMeas_SignLatest(MEAS_CH_IN, (strong != 0U) ? MEAS_GUARD_STRONG_COUNTS : MEAS_GUARD_MIN_COUNTS);
}

int8_t CtrlHw_Sign(uint8_t out_channel, int32_t *dev_sum)
{
    return SlaveMeas_SignBeforeNow((out_channel != 0U) ? MEAS_CH_OUT : MEAS_CH_IN, dev_sum);
}

void CtrlHw_GetMeas(CtrlMeas_t *m)
{
    m->vin          = g_meas.vrms_in;
    m->vout         = g_meas.vrms_out;
    m->update_count = g_meas.update_count;
    m->valid        = g_meas.valid;
}

uint32_t CtrlHw_Lock(void)
{
    uint32_t primask = __get_PRIMASK();
    __disable_irq();
    return primask;
}

void CtrlHw_Unlock(uint32_t previous)
{
    if (previous == 0U) __enable_irq();
}

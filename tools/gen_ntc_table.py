#!/usr/bin/env python3
"""Generates master/Core/Src/m_ntc_table.h: the slave's NTC reading (12 bit ADC count of PA5) against temperature.
The circuit: 3.3 V -- R_FIXED -- PA5 -- NTC -- GND (the ADC reference is the same 3.3 V, so the reading is ratiometric: raw = 4095 x R_ntc / (R_ntc + R_fixed)).
The NTC follows the beta equation: R = R0 x exp(B x (1/T - 1/T0)).  Usage: tools/gen_ntc_table.py [B] [R0] [R_FIXED]   (defaults 3950, 10000, 1500)"""
import math, sys
B = float(sys.argv[1]) if len(sys.argv) > 1 else 3950.0
R0 = float(sys.argv[2]) if len(sys.argv) > 2 else 10000.0
RF = float(sys.argv[3]) if len(sys.argv) > 3 else 1500.0
T_FIRST, T_STEP, N = -10, 5, 29            # -10 ... +130 degC
def raw_at(tc):
    t = tc + 273.15; r = R0 * math.exp(B * (1.0 / t - 1.0 / 298.15))
    return int(round(4095.0 * r / (r + RF)))
vals = [raw_at(T_FIRST + i * T_STEP) for i in range(N)]
print("/* Generated by tools/gen_ntc_table.py (B = %g, R0 = %g ohm at 25 degC, R_FIXED = %g ohm to 3.3 V). Do not edit by hand. */" % (B, R0, RF))
print("#define MNTC_T_FIRST_C   (%d)" % T_FIRST)
print("#define MNTC_T_STEP_C    %d" % T_STEP)
print("#define MNTC_N           %d" % N)
print("static const uint16_t s_ntc_raw[MNTC_N] = {   /* the reading at -10, -5, 0 ... 130 degC (falls as the NTC heats up) */")
for i in range(0, N, 8): print("    " + ", ".join("%u" % v for v in vals[i:i + 8]) + ",")
print("};")
